/**
 * Коэффициент корректировки количества по брокеру.
 *
 * Когда журнал и брокер расходятся в штуках, честных объяснений два: в журнале
 * не хватает сделок (тогда чинить сделками) или не хватает корпоративного
 * действия (тогда чинить сплитом). Эта функция — вторая ветка: коэффициент
 * `цель/текущее` превращает расхождение в эквивалент неучтённой консолидации,
 * и FIFO-движок сам пересчитывает и количество, и среднюю цену лотов, не
 * трогая себестоимость и реализованную историю.
 */

export interface QuantityCorrection {
  /** Коэффициент для операции «Сплит»: журнальное количество × ratio = целевое. */
  ratio: number;
}

/** null — корректировка бессмысленна или опасна, причина в сообщении. */
export function correctionRatio(
  ledgerQuantity: number,
  brokerQuantity: number,
): { ratio: number } | { error: string } {
  if (!(ledgerQuantity > 0)) {
    return { error: "В журнале нулевое количество — нечего масштабировать." };
  }
  if (!(brokerQuantity >= 0)) {
    return { error: "Количество у брокера не может быть отрицательным." };
  }

  const ratio = brokerQuantity / ledgerQuantity;

  // Совпадение в пределах погрешности — корректировать нечего.
  if (Math.abs(1 - ratio) < 1e-9) {
    return { error: "Количества уже совпадают." };
  }

  // Коэффициент больше единицы — это «сплит наоборот»: он увеличивает
  // количество. Для неучтённой консолидации (VTBR) нужен ratio < 1; увеличение
  // чаще означает усечённую историю покупок, и её надо чинить сделками или
  // стартовыми позициями, а не масштабированием.
  if (ratio > 1) {
    return {
      error:
        "У брокера бумаг больше, чем в журнале — это не консолидация, а пропущенные " +
        "покупки. Добавьте их стартовой позицией или полной синхронизацией.",
    };
  }

  // Коэффициент до брокера = 0 допустим (списание), но настолько экстремальные
  // значения почти всегда означают ошибку в данных, а не корпоративное действие.
  if (brokerQuantity > 0 && ratio < 1e-6) {
    return {
      error:
        "Коэффициент меньше миллионной — так не выглядит ни одно корпоративное " +
        "действие. Сначала разберитесь, откуда в журнале это количество.",
    };
  }

  return { ratio };
}
